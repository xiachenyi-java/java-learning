public class a5数据类型 {
    public static void main(String[] args) {
        int a = 1;
        //整数用 int
        System.out.println(a);
        double b =1.1;
        //小数用 double
        System.out.println(b);
        char c = '夏';
        //字符用 char
        System.out.println(c);
        String d = "夏辰义";
        //字符串用 String
        System.out.println(d);
        System.out.println("这次学习效果是"+a);
        //+是用来拼接数字和中文的
        System.out.println(a+"我真聪明");
        //+前后不影响作用
    }
}
