public class a16作用域 {
    public static void main(String[] args) {
        A a = new A();
        a.A1();
        a.A2();
    }
    static class A {
        int i = 2;
        public void A1(){
            int j = 3;
            System.out.println("对象里的属性是" + i + "方法里的变量是" + j);
        }
        public void A2(){
            int j = 4;
            System.out.println("对象里的属性是" + i + "方法里的变量是" + j);
        }
    }
}
/*
对象里的属性是全局变量，可以不赋值默认为0
但方法里的变量是局部变量，必须赋值
所以A1和A2是有两个一样名字的变量但是互相不影响
类型	      声明位置	  作用范围	            生命周期
类作用域	     static成员	整个类，所有实例共享	类加载到程序结束
实例作用域	非static成员	当前实例对象	        对象创建到被回收
局部作用域	方法或代码块内	声明处到代码块结束	    进入代码块到退出
参数作用域	方法参数列表	整个方法体	        方法调用期间
查找顺序：局部 → 实例 → 类
this关键字：区分实例变量和局部变量
生命周期：局部变量栈分配，实例/类变量堆分配
最佳实践：缩小变量作用域，避免不必要的遮蔽
属性和局部变量可以重名，调用时就近原则
 */
