package com.A2CodeBlock;

public class T1Tset {
    public static void main(String[] args) {
        T1 t1 = new T1();
        System.out.println("========");
        T1 t2 = new T1(10);
        System.out.println("========");
        T2 t3 = new T2();
        System.out.println("========");
        new T2(20,51);
    }
}
/*
| 类型        | 语法            | 执行时机   | 次数        |
| --------- | ------------- | ------ | --------- |
| **静态代码块** | `static{...}` | 类加载时   | **仅1次**   |
| **普通代码块** | `{...}`       | 每次实例化时 | **每次new** |

【类加载阶段】（整个程序只执行一次）
    父类静态代码块 → 子类静态代码块

【实例化阶段】（每次new都执行）
    父类普通代码块（按书写顺序）
    → 父类构造器（由super()决定）
    → 子类普通代码块（按书写顺序）
    → 子类构造器
    | 规则         | 说明                        |
| ---------- | ------------------------- |
| 静态只执行一次    | 类加载时触发，后续new对象不再执行        |
| 普通代码块每次执行  | 编译器将其插入每个构造器最前面           |
| 多个代码块按书写顺序 | 先写的先执行                    |
| 子类构造器默认第一行 | `super()`，即调用父类无参构造       |
| 父类只有有参构造器  | 子类必须显式写`super(参数)`，否则编译报错 |

"静一次，普每次，先父后子，块在构前，super定父构"
静一次	静态代码块只执行1次
普每次	普通代码块每次new都执行
先父后子	父类全部完成后才执行子类
块在构前	同类中代码块在构造器之前
super定父构	super()或super(参数)决定调用父类哪个构造器
 */
