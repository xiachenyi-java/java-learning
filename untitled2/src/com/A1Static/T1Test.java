package com.A1Static;

public class T1Test {
    public static void main(String[] args) {
        T1.i++;
        T1.A1();
        T1 t1 = new T1();
        t1.j++;
        t1.A2();
    }//执行顺序：静态变量/代码块（类加载时）→ 实例变量 → 构造方法
}
/*
1. static 关键字
类型	说明	访问方式
静态变量	属于类，所有实例共享	类名.变量名
静态方法	属于类，不依赖实例	类名.方法名()
静态代码块	类加载时执行，只执行一次	自动执行
静态内部类	不依赖外部类实例	外部类.内部类
核心区别：静态属于类，非静态属于对象（实例)
静态变量在类加载时分配内存，程序结束才释放
实例变量在new 对象时分配内存，对象被回收时释放
访问规则（重要！）
访问方向	是否允许	示例
静态方法 → 静态变量	✅ 允许	A1() 访问 i
静态方法 → 实例变量	❌ 不允许	A1() 不能直接访问 j
实例方法 → 静态变量	✅ 允许	A2() 访问 i
实例方法 → 实例变量	✅ 允许	A2() 访问 j
为什么静态方法不能访问实例变量？因为静态方法调用时可能还没有创建对象，实例变量不存在。
常见面试题/陷阱
陷阱 1：静态方法里用 this
public static void A1() {
    this.i++;  // ❌ 编译错误！静态方法没有 this,也没有super
}
陷阱 2：静态变量的线程安全
T1.i++;  // 多线程下不安全，需要同步
陷阱 3：静态导入
import static java.lang.Math.*;  // 可直接用 PI、random() 等
 */