public class 冒泡排序 {
    public static void main(String[] args) {
        int[] A = {23,51,1422,24,15};
        int i, j, a,b;
        for(i = 0;i < A.length - 1;i++){  //j < 4 - i 这个优化不止是性能，更是体现了"每轮冒泡后减少比较范围"的算法思想。
            for (j = 0; j < A.length - 1; j++) {
                if (A[j] < A[j + 1]) {
                    a = A[j];
                    A[j] = A[j + 1];
                    A[j + 1] = a;
                }
            }
        }
        for (b = 0; b < A.length; b++) {
            System.out.print(A[b] + " ");
        }
    }
}
//13-冒泡排序
//需求
//将无序的数组变成有序（从小到大或从大到小），这是数据结构最基础的需求。比如成绩排名、商品按价格排序。
//核心思路（想象成水底冒泡泡）
//核心规则：相邻比较，大的往后冒。每一轮都把当前最大的数"冒泡"到数组末尾。
//执行流程：
//第一轮：从第一个元素开始，逐个比较相邻的两个数。如果前面的比后面的大，就交换位置。走完一轮，最大的数一定在最后一个位置。
//第二轮：前 n-1 个数重复上述过程（最后一个数已经排好，不用管）。此时第二大的数在倒数第二的位置。
//继续重复：每轮让未排序部分的最大值"冒泡"到正确位置。
//终止条件：经过 n-1 轮后，所有数都有序。
//优化思路：如果某一轮没有任何交换，说明数组已经有序，可以提前结束，避免无效循环